// Run with NODE_PATH pointing to an installation of playwright; serve the repo at :8765.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium'});
  const context = await browser.newContext({viewport:{width:390,height:844}});
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.hostname === '127.0.0.1') return route.continue();
    if (url.hostname.endsWith('.supabase.co')) return route.fulfill({json:[]});
    return route.abort();
  });
  const page = await context.newPage();
  const errors=[]; page.on('pageerror', error => errors.push(error.message));
  const base='http://127.0.0.1:8765';
  await page.goto(base+'/?lang=wo');
  await page.waitForFunction(()=>document.documentElement.lang==='wo');
  await page.waitForFunction(()=>document.querySelector('a[href*="saly.html"]').href.includes('lang=wo'));
  await page.goto(base+'/menu-universel-v1.html?lang=wo');
  assert.equal(await page.getAttribute('html','lang'),'wo');
  await page.goto(base+'/saly.html'); // saved language is inherited
  assert.equal(await page.getAttribute('html','lang'),'wo');
  assert.match(await page.locator('#salyPublicQuestion').innerText(),/Lan ngay seet/);
  assert.match(await page.locator('#needs').innerText(),/DEM AK DIKK/);
  assert.match(await page.locator('#cards').innerText(),/WEER|weer/);
  await page.waitForFunction(()=>document.querySelector('#realGrid').textContent.includes('Amagul'));
  const find=await page.locator('[data-lien="find"]').getAttribute('href');
  assert.equal(new URL(find).searchParams.get('lang'),'wo');
  assert.equal(new URL(find).searchParams.get('city'),'Saly');
  assert.match(await page.locator('a[href*="partenaire-lamine"]').first().getAttribute('href'),/lang=wo/);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path:'/tmp/digiy-saly-wo.png',fullPage:false});
  await page.goto(base+'/recherche.html?city=Saly&lang=wo');
  await page.waitForFunction(()=>!document.getElementById('submitBtn').disabled);
  assert.equal(await page.locator('#city').inputValue(),'Saly');
  assert.equal(await page.locator('#submitBtn').innerText(),'Seet');
  await page.locator('#query').fill('dawalkat');
  await page.locator('#submitBtn').click();
  await page.waitForFunction(()=>document.querySelector('#count').textContent.includes('lañu gis'));
  assert.match(await page.locator('#results').innerText(),/Lamine/);
  const wa=await page.locator('[data-digiy-official="lamine"] .btnWhatsapp').getAttribute('href');
  assert.equal(new URL(wa).hostname,'wa.me');
  assert(!new URL(wa).searchParams.has('lang'));
  assert.match(new URL(wa).searchParams.get('text'),/Salaam aleekum/);
  assert.match(await page.locator('[data-digiy-official="lamine"] .btnPrimary').getAttribute('href'),/lang=wo/);
  await page.locator('#module').selectOption('DRIVER');
  await page.locator('[data-l="fr"]').click();
  assert.equal(await page.locator('#module').inputValue(),'DRIVER');
  assert.equal(await page.locator('#city').inputValue(),'Saly');
  await page.locator('[data-l="wo"]').click();
  await page.locator('#query').fill('introuvable-xyz');
  await page.locator('#module').selectOption('');
  await page.locator('#submitBtn').click();
  assert.match(await page.locator('#status').innerText(),/Amul/);
  await page.locator('[data-l="ar"]').click();
  assert.equal(await page.getAttribute('html','dir'),'rtl');
  await page.locator('[data-l="wo"]').click();
  assert.equal(await page.getAttribute('html','dir'),'ltr');
  await page.screenshot({path:'/tmp/digiy-recherche-wo.png',fullPage:false});
  await page.goto(base+'/saly.html?lang=fr');
  assert.equal(await page.getAttribute('html','lang'),'fr');
  assert.match(await page.locator('#salyPublicQuestion').innerText(),/Vous cherchez/);
  const blocked = await browser.newContext();
  await blocked.addInitScript(()=>{Object.defineProperty(window,'localStorage',{get(){throw new Error('blocked')}})});
  const offline=await blocked.newPage();
  await offline.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.fulfill({json:[]}));
  await offline.goto(base+'/saly.html?lang=wo');
  assert.equal(await offline.getAttribute('html','lang'),'wo');
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: mobile WO journey, aliases, contacts, empty state, FR/AR, filters, storage denied');
})().catch(error=>{console.error(error);process.exit(1)});
